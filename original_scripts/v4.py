import os
import re
import time
import wave
import tempfile
import threading
from datetime import timedelta

import numpy as np
import sounddevice as sd
import torch
from nemo.collections.asr.models import ASRModel


# ============================================================
# SETTINGS
# ============================================================

SAMPLE_RATE = 16000
CHANNELS = 1

# How much audio to process at a time.
CHUNK_SECONDS = 4.0

# Audio overlap between chunks.
# This helps prevent words at the boundary from being cut off.
OVERLAP_SECONDS = 0.75

OUTPUT_FILE = "transcription.txt"

MODEL_NAME = "KlangAI/pianissimo-sv"


# ============================================================
# GLOBAL STATE
# ============================================================

audio_buffer = []
buffer_lock = threading.Lock()

running = True
recording_start = time.time()

# Last text generated by the previous chunk.
previous_text = ""


# ============================================================
# LOAD MODEL
# ============================================================

print("Loading Pianissimo...")

device = torch.device("cuda" if torch.cuda.is_available() else "cpu")

print(f"Using device: {device}")

model = ASRModel.from_pretrained(
    model_name=MODEL_NAME,
    map_location=device,
).eval()

print("Pianissimo loaded.")
print()


# ============================================================
# AUDIO CALLBACK
# ============================================================

def audio_callback(indata, frames, time_info, status):
    if status:
        print(f"[Audio] {status}")

    if not running:
        return

    audio = indata[:, 0].copy()

    with buffer_lock:
        audio_buffer.extend(audio)


# ============================================================
# TEXT CLEANUP / OVERLAP REMOVAL
# ============================================================

def normalize_text(text):
    """
    Normalize text for comparing overlapping chunks.
    """
    text = text.lower()
    text = re.sub(r"\s+", " ", text)
    return text.strip()


def remove_overlap(previous, current):
    """
    Try to remove words that were already printed because
    the audio chunks overlap.

    Example:

        previous:
        "jag tänkte att vi skulle"

        current:
        "vi skulle gå till affären"

    becomes:

        "gå till affären"
    """

    if not previous or not current:
        return current.strip()

    prev_words = normalize_text(previous).split()
    curr_words = current.split()

    if not prev_words or not curr_words:
        return current.strip()

    # Look for the longest suffix of the previous transcription
    # that is also a prefix of the current transcription.
    max_overlap = min(len(prev_words), len(curr_words), 12)

    best_overlap = 0

    for n in range(1, max_overlap + 1):
        prev_part = prev_words[-n:]
        curr_part = [
            normalize_text(x)
            for x in curr_words[:n]
        ]

        if prev_part == curr_part:
            best_overlap = n

    if best_overlap:
        return " ".join(curr_words[best_overlap:]).strip()

    return current.strip()


# ============================================================
# SAVE TRANSCRIPTION
# ============================================================

def save_text(text, timestamp):
    if not text:
        return

    with open(OUTPUT_FILE, "a", encoding="utf-8") as f:
        f.write(f"[{timestamp}] {text}\n")
        f.flush()


# ============================================================
# TRANSCRIBE AUDIO
# ============================================================

def transcribe_audio(audio):
    global previous_text

    if len(audio) == 0:
        return

    # Make sure the audio is float32.
    audio = np.asarray(audio, dtype=np.float32)

    # NeMo expects 16 kHz mono audio.
    audio = np.clip(audio, -1.0, 1.0)

    try:
        with torch.inference_mode():
            hypotheses = model.transcribe(
                audio=[audio],
                batch_size=1,
                return_hypotheses=True,
            )

        if not hypotheses:
            return

        result = hypotheses[0]

        if hasattr(result, "text"):
            text = result.text
        else:
            text = str(result)

        text = text.strip()

        if not text:
            return

        # Remove words duplicated because of the overlap.
        new_text = remove_overlap(previous_text, text)

        previous_text = text

        if not new_text:
            return

        elapsed = time.time() - recording_start
        timestamp = str(timedelta(seconds=int(elapsed)))

        print(f"[{timestamp}] {new_text}")

        save_text(new_text, timestamp)

    except Exception as e:
        print(f"\n[ERROR] Transcription failed: {e}\n")


# ============================================================
# PROCESSING THREAD
# ============================================================

def processing_loop():
    global running

    chunk_samples = int(CHUNK_SECONDS * SAMPLE_RATE)
    overlap_samples = int(OVERLAP_SECONDS * SAMPLE_RATE)

    # Amount of audio that must accumulate before processing.
    required_samples = chunk_samples * SAMPLE_RATE // 1

    while running:

        time.sleep(0.05)

        with buffer_lock:

            if len(audio_buffer) < chunk_samples:
                continue

            # Take a chunk.
            audio = np.array(
                audio_buffer[:chunk_samples],
                dtype=np.float32
            )

            # Keep the overlap for the next chunk.
            del audio_buffer[:chunk_samples - overlap_samples]

        transcribe_audio(audio)


# ============================================================
# MAIN
# ============================================================

def main():
    global running
    global recording_start

    # Start a fresh transcription file.
    with open(OUTPUT_FILE, "w", encoding="utf-8") as f:
        f.write("Pianissimo real-time transcription\n")
        f.write("=" * 40 + "\n\n")

    print("=" * 60)
    print("Pianissimo real-time Swedish transcription")
    print("=" * 60)
    print()
    print(f"Output file: {os.path.abspath(OUTPUT_FILE)}")
    print(f"Chunk size:  {CHUNK_SECONDS} seconds")
    print(f"Overlap:     {OVERLAP_SECONDS} seconds")
    print()
    print("Speak into your microphone.")
    print("Press Ctrl+C to stop.")
    print()

    recording_start = time.time()

    processing_thread = threading.Thread(
        target=processing_loop,
        daemon=True
    )

    processing_thread.start()

    try:
        with sd.InputStream(
            samplerate=SAMPLE_RATE,
            channels=CHANNELS,
            dtype="float32",
            blocksize=1600,
            callback=audio_callback,
        ):
            while True:
                time.sleep(0.1)

    except KeyboardInterrupt:
        print("\nStopping...")

    finally:
        running = False
        processing_thread.join(timeout=5)

        print()
        print(f"Transcription saved to:")
        print(os.path.abspath(OUTPUT_FILE))


if __name__ == "__main__":
    main()